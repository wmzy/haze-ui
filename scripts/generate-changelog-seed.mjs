// One-time CHANGELOG.md seeder: pulls every published GitHub Release from
// wmzy/haze-ui and renders a Keep a Changelog-style history. Run once;
// afterwards semantic-release (@semantic-release/changelog) prepends new
// entries under the same "# Changelog" title, so the formats stay compatible.
//
// Usage: node scripts/generate-changelog-seed.mjs [--out CHANGELOG.md]
//
// Primary source: `gh api repos/wmzy/haze-ui/releases --paginate --jq ...`.
// Fallback (no gh / no network): `git tag` list with placeholder bodies.
// If neither works the script exits non-zero with an explanation.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const REPO = 'wmzy/haze-ui';
const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const outPath = outIndex !== -1 ? args[outIndex + 1] : 'CHANGELOG.md';

const HEADER = `# Changelog

All notable changes to this project will be documented in this file.

The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/),
and this project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).

Entries up to the seed date were imported from [GitHub Releases](${RELEASES_URL()});
newer entries are generated by [semantic-release](https://github.com/semantic-release/semantic-release).
`;

function RELEASES_URL() {
  return `https://github.com/${REPO}/releases`;
}

function run(cmd) {
  return execFileSync(cmd[0], cmd.slice(1), {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
}

// --- source 1: GitHub Releases via gh CLI -------------------------------

// `gh api --paginate --jq '.[] | {...}'` emits one compact JSON object per
// release per page (JSONL), so pages need no merging logic.
function fetchViaGh() {
  const stdout = run([
    'gh',
    'api',
    `repos/${REPO}/releases`,
    '--paginate',
    '--jq',
    '.[] | {tag_name, name, published_at, prerelease, html_url, body}',
  ]);
  return stdout
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .map((line) => JSON.parse(line));
}

// --- source 2: git tags (bodies unavailable) -----------------------------

function fetchViaGit() {
  const tags = run(['git', 'tag', '--list', 'v*', '--sort=-creatordate'])
    .split('\n')
    .map((t) => t.trim())
    .filter((t) => /^v\d+\.\d+\.\d+$/.test(t));
  return tags.map((tag) => {
    const date = run(['git', 'log', '-1', '--format=%as', tag]).trim();
    return {
      tag_name: tag,
      published_at: date ? `${date}T00:00:00Z` : null,
      body: '_Release notes unavailable (seeded from git tags without GitHub Releases access). See the GitHub Releases page for details._',
      html_url: `https://github.com/${REPO}/releases/tag/${tag}`,
    };
  });
}

// --- rendering ------------------------------------------------------------

function normalizeTag(tag) {
  return tag.startsWith('v') ? tag : `v${tag}`;
}

// semantic-release-written release bodies open with their own version heading
// ("# [1.2.3](compare-url) (date)" or "## [...]"), which duplicates the
// section header rendered above. Drop it, then demote any remaining H1/H2 to
// H3 so everything nests under the "## [tag]" sections. Lines inside fenced
// code blocks are left untouched.
function normalizeBody(body, bareVersion) {
  const raw = body.trim() || '_No release notes._';
  const lines = raw.split('\n');
  if (lines.length > 0 && /^#{1,3} /.test(lines[0]) && lines[0].includes(bareVersion)) {
    lines.shift();
    while (lines.length > 0 && lines[0].trim() === '') lines.shift();
  }
  let inFence = false;
  return lines
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
      if (!inFence && /^#{1,2} [^#]/.test(line)) return line.replace(/^#{1,2}/, '###');
      return line;
    })
    .join('\n')
    .trimEnd();
}

function renderEntry(release) {
  const tag = normalizeTag(release.tag_name);
  const date = release.published_at ? release.published_at.slice(0, 10) : 'YYYY-MM-DD';
  const body = normalizeBody(release.body ?? '', tag.replace(/^v/, ''));
  const lines = [
    `## [${tag}](${release.html_url ?? `${RELEASES_URL()}/tag/${tag}`}) - ${date}`,
    '',
    ...body.split('\n').map((l) => l.trimEnd()),
    '',
  ];
  return lines.join('\n');
}

function main() {
  let releases = null;
  let source = '';
  try {
    releases = fetchViaGh();
    source = 'GitHub Releases (gh api)';
  } catch (err) {
    console.warn(`[seed] gh api failed (${err.message.split('\n')[0]}); falling back to git tags`);
    try {
      releases = fetchViaGit();
      source = 'git tags (no bodies)';
    } catch (gitErr) {
      console.error(
        `[seed] Could not build the changelog seed:\n` +
          `  - gh api repos/${REPO}/releases failed: ${err.message.split('\n')[0]}\n` +
          `  - git tag fallback failed: ${gitErr.message.split('\n')[0]}\n` +
          'Install and authenticate the GitHub CLI (gh auth login) or run inside the git repository.',
      );
      process.exit(1);
    }
  }

  if (!Array.isArray(releases) || releases.length === 0) {
    console.error('[seed] No releases found; refusing to write an empty changelog.');
    process.exit(1);
  }

  const sorted = [...releases].sort((a, b) =>
    (b.published_at ?? '').localeCompare(a.published_at ?? ''),
  );

  const content = `${HEADER}\n${sorted.map(renderEntry).join('\n')}`;
  writeFileSync(outPath, `${content.trimEnd()}\n`, 'utf8');
  console.log(
    `[seed] Wrote ${outPath}: ${sorted.length} releases (${sorted[sorted.length - 1].tag_name} → ${sorted[0].tag_name}), source: ${source}.`,
  );
}

main();
